def get_condition_knowledge(condition_name: str, language: str = "english") -> dict:
    lang = (language or "english").lower().strip()
    if lang not in ["english", "hindi", "hinglish"]:
        lang = "english"

    matched_data = None
    for key, data in MEDICAL_KNOWLEDGE_BASE.items():
        if key.lower() in condition_name.lower() or condition_name.lower() in key.lower():
            matched_data = data
            break

    if matched_data:
        res = matched_data.get(lang) or matched_data.get("english")
        return dict(res)
    
    return dict(DEFAULT_KNOWLEDGE.get(lang) or DEFAULT_KNOWLEDGE.get("english"))


def get_all_language_knowledge(condition_name: str) -> dict:
    """Returns knowledge dictionary for all 3 supported languages (english, hindi, hinglish)."""
    return {
        "english": get_condition_knowledge(condition_name, "english"),
        "hindi": get_condition_knowledge(condition_name, "hindi"),
        "hinglish": get_condition_knowledge(condition_name, "hinglish")
    }

